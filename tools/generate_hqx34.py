"""Generate the C# HQx 3x/4x pattern switches from the 4DO reference sources.

Usage (from the repository root):

    python tools/generate_hqx34.py

The generated files are checked in so builds do not need Python or the reference
sources. They are derived from Maxim Stepin's hq3x/hq4x and Cameron Zemek's C port
(LGPL 2.1+); see THIRD-PARTY-NOTICES.md.
"""
import re
import sys

ROOT = 'References/4DO-master/FreeDOCore/Filters'
OUT = 'src/ThreeDo.Video.OpenGL'


def parse_macros(source):
    macros = {}
    for m in re.finditer(r'#define\s+(PIXEL\d\d)(?:_(\w+))?\s+(.+)', source):
        macros[(m.group(1), m.group(2) or '')] = m.group(3).strip()
    return macros


def macro_expression(body):
    body = body.strip().rstrip(';').strip()
    if body.startswith('*'):
        # Direct assignment; the right side is w[5].
        return body.split('=', 1)[1].strip()
    m = re.match(r'(Interp\d+)\(dp(?:\+[^,]+)?,\s*(.*)\)$', body)
    if not m:
        raise ValueError('Unrecognized macro: ' + body)
    return f'{m.group(1)}({m.group(2)})'


def switch_body(source):
    start = source.index('switch (pattern)')
    brace = source.index('{', start)
    depth = 0
    for i in range(brace, len(source)):
        if source[i] == '{':
            depth += 1
        elif source[i] == '}':
            depth -= 1
            if depth == 0:
                return source[brace + 1:i]
    raise ValueError('unterminated switch')


def translate_case(body, macros, scale):
    lines = []
    for raw in body.splitlines():
        line = raw.strip()
        if not line or line.startswith('//'):
            continue
        if line == 'break;':
            lines.append('break;')
            continue
        if line.startswith('if (Diff('):
            lines.append(line)
            continue
        if line in ('{', '}', 'else', 'else {'):
            lines.append(line)
            continue
        m = re.match(r'PIXEL(\d\d)(?:_(\w+))?$', line)
        if not m:
            raise ValueError('Unrecognized statement: ' + line)
        pixel = m.group(1)
        suffix = m.group(2) or ''
        expr = macro_expression(macros[(f'PIXEL{pixel}', suffix)])
        index = int(pixel[0]) * scale + int(pixel[1])
        lines.append(f'o[{index}] = {expr};')
    return lines


def generate(name, scale):
    source = open(f'{ROOT}/{name}.cpp', encoding='utf-8-sig').read()
    macros = parse_macros(source)
    body = switch_body(source)
    cases = []
    for m in re.finditer(r'case\s+(\d+)\s*:', body):
        number = int(m.group(1))
        brace = body.find('{', m.end())
        depth = 0
        case_body = ''
        for i in range(brace, len(body)):
            if body[i] == '{':
                depth += 1
            elif body[i] == '}':
                depth -= 1
                if depth == 0:
                    case_body = body[brace + 1:i]
                    break
        cases.append((number, translate_case(case_body, macros, scale)))

    header = f'''// <auto-generated />
// HQx {scale}x pattern switch derived from Maxim Stepin's hq{scale}x and Cameron
// Zemek's C port (LGPL 2.1+). See the header of HqxFilter.cs and
// THIRD-PARTY-NOTICES.md. Regenerate with tools/generate_hqx34.py.
namespace ThreeDo.Video.OpenGL;

public sealed partial class HqxFilter
{{
    private void ApplyPattern{scale}(int pattern, uint[] w)
    {{
        var o = _patternOutput;
        switch (pattern)
        {{
'''
    footer = '''        }
    }
}
'''
    output = [header]
    for number, lines in cases:
        output.append(f'            case {number}:\n')
        for line in lines:
            output.append(f'                {line}\n')
    output.append(footer)
    path = f'{OUT}/HqxPatterns{scale}.cs'
    with open(path, 'w', encoding='utf-8', newline='\n') as file:
        file.write(''.join(output))
    print(f'wrote {path} ({len(cases)} cases)')


if __name__ == '__main__':
    if len(sys.argv) > 1 and sys.argv[1] == 'hq3x':
        generate('hq3x', 3)
    elif len(sys.argv) > 1 and sys.argv[1] == 'hq4x':
        generate('hq4x', 4)
    else:
        generate('hq3x', 3)
        generate('hq4x', 4)
